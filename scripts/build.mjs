// Writes src/inline.js: the popup's page with its CSS and scripts inside it,
// for hosts that show it without serving popup/ themselves. Run it after
// changing anything in popup/ (`npm run build`); `npm test` fails if it's stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => readFileSync(join(root, "popup", name), "utf8");
// A script's text can't hold "</script": the page would end it there.
const script = (name) => `<script>${read(name).replaceAll("</script", "<\\/script")}</script>`;

export function inlinePage() {
  return `<!doctype html>
<html data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1.0">
<style>${read("base.css")}</style>
<style id="dictionary-styles"></style>
</head>
<body>
<main id="entries" class="entries"></main>
${script("kanji-renderer.js")}
${script("renderer.js")}
</body>
</html>
`;
}

export function inlineModule() {
  return `// Generated by scripts/build.mjs from popup/. Don't edit it: change popup/ and run \`npm run build\`.\nexport const POPUP_HTML = ${JSON.stringify(inlinePage())};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "src", "inline.js"), inlineModule());
  console.log("src/inline.js written");
}
